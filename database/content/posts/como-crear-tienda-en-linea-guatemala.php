<p>Vender en línea en Guatemala no es lo mismo que en México o en España, y las guías que se encuentran en internet casi siempre están escritas para otro país. Acá hay particularidades concretas: cómo cobra la gente, qué esperan del envío al interior, qué pide la SAT y qué pasarelas de pago funcionan de verdad.</p>
<p>Esta guía es el orden en que nosotros montamos una tienda, con las decisiones que hay que tomar en cada paso.</p>

<h2>Paso 1: Confirmá que tu negocio está listo</h2>
<p>Antes de gastar un quetzal, contestá tres preguntas honestamente:</p>
<ul>
  <li><strong>¿Podés controlar tu inventario?</strong> Si no sabés cuántas unidades tenés de cada producto, la tienda va a generar pedidos que no vas a poder cumplir. Eso cuesta clientes y reseñas.</li>
  <li><strong>¿Alguien va a mantener la tienda?</strong> Actualizar precios, marcar productos agotados, revisar pedidos. Media hora al día como mínimo.</li>
  <li><strong>¿Tenés cómo despachar?</strong> Aunque sea un acuerdo con un mensajero. Sin logística resuelta, la tienda solo traslada el problema.</li>
</ul>
<p>Si alguna respuesta es no, empezá con un catálogo en línea sin carrito, donde la gente pide por WhatsApp. Es un paso intermedio perfectamente válido.</p>

<h2>Paso 2: Elegí y registrá el dominio</h2>
<p>El nombre de tu tienda en internet. Para vender a Guatemala, un <code>.com</code> funciona bien y es lo más económico; un <code>.gt</code> o <code>.com.gt</code> transmite cercanía local. Lo importante es que sea corto, fácil de dictar por teléfono y sin guiones ni números.</p>
<p>Registralo a nombre de tu empresa, no del proveedor que te arma la tienda. Es tu activo. Escribimos aparte sobre <a href="/blog/dominio-gt-como-registrarlo/">cómo funciona el dominio .gt y cómo registrarlo</a>.</p>

<h2>Paso 3: Escogé la plataforma</h2>
<p>Las opciones realistas para un negocio guatemalteco son tres:</p>
<ul>
  <li><strong>WooCommerce</strong> sobre WordPress. Se instala en tu propio alojamiento, no cobra comisión por venta y podés llevártelo a donde quieras. Es lo que usamos nosotros.</li>
  <li><strong>Shopify.</strong> Renta mensual en dólares, muy fácil de usar, pero con limitaciones para integrar pasarelas locales. Lo comparamos a fondo en <a href="/blog/woocommerce-vs-shopify-guatemala/">WooCommerce o Shopify para negocios en Guatemala</a>.</li>
  <li><strong>Marketplaces</strong> como Kemik o los perfiles de compra de redes sociales. Sirven para probar demanda sin inversión, pero no son tuyos y las reglas las pone otro.</li>
</ul>
<p>Un consejo: podés estar en un marketplace y tener tu tienda propia al mismo tiempo. No son excluyentes.</p>

<h2>Paso 4: Contratá alojamiento que aguante</h2>
<p>Una tienda pesa más que una página informativa y hace consultas constantes a la base de datos. El plan de alojamiento más barato del mercado no va a servir: cuando lances una promoción y entren cincuenta personas a la vez, la tienda se cae justo el día que más te importa.</p>
<p>Buscá un plan con certificado SSL incluido, respaldos automáticos y soporte que conteste. Si tu público está en Guatemala, un servidor en Estados Unidos funciona bien; la diferencia de milisegundos con un servidor local no se nota.</p>

<h2>Paso 5: Armá el catálogo bien desde el inicio</h2>
<p>Este paso decide si tu tienda vende o no. Cada producto necesita:</p>
<ul>
  <li><strong>Nombre claro,</strong> como lo busca la gente, no como lo llaman internamente en tu bodega.</li>
  <li><strong>Foto propia,</strong> sobre fondo claro y parejo. Con un celular reciente y luz de día alcanza. Evitá las fotos que el proveedor te manda por WhatsApp con su marca de agua.</li>
  <li><strong>Descripción que responda dudas:</strong> medidas, material, contenido del empaque, garantía, para qué sirve.</li>
  <li><strong>Precio y existencias reales.</strong></li>
  <li><strong>Variantes</strong> cuando aplique: talla, color, presentación.</li>
  <li><strong>Categorías</strong> pensadas como las buscaría un cliente, no como está organizada tu bodega.</li>
</ul>
<p>Empezá con tus veinte productos que más rotan. Es mejor una tienda con veinte productos bien presentados que una con trescientos a medias.</p>

<h2>Paso 6: Definí los envíos con números</h2>
<p>Esta es la parte donde más tiendas guatemaltecas improvisan. Necesitás decidir:</p>
<ul>
  <li>Cuánto cobrás dentro de la ciudad capital.</li>
  <li>Cuánto cobrás al interior, y si vas a diferenciar por departamento o poner una tarifa única.</li>
  <li>Si ofrecés envío gratis a partir de cierto monto, y si ese monto te deja margen.</li>
  <li>Si permitís retiro en tienda o punto de encuentro.</li>
  <li>En cuántos días entregás, y decilo en el sitio.</li>
</ul>
<p>Configurá esas reglas en la tienda para que el cliente vea el costo de envío <strong>antes</strong> de confirmar. Sorprender con el costo de envío al final es de las principales razones por las que se abandona un carrito.</p>

<h2>Paso 7: Habilitá formas de pago que la gente use</h2>
<p>En Guatemala, la combinación que mejor funciona al arrancar es esta:</p>
<ul>
  <li><strong>Depósito o transferencia bancaria</strong> con carga del comprobante. Es lo más usado y no tiene costo por transacción.</li>
  <li><strong>Pago contra entrega</strong> en efectivo. Genera confianza en clientes que compran por primera vez, aunque implica riesgo de pedidos falsos.</li>
  <li><strong>Tarjeta de crédito y débito</strong> mediante una pasarela. La opción más común es Visanet Epay, y requiere afiliación con un banco. Lo explicamos en <a href="/blog/como-cobrar-con-tarjeta-sitio-web-guatemala/">cómo cobrar con tarjeta en tu sitio web</a>.</li>
</ul>
<p>Nuestra recomendación: arrancá con transferencia y contra entrega, medí cuántos pedidos entran al mes y activá la tarjeta cuando el volumen justifique la afiliación y su comisión.</p>

<h2>Paso 8: Resolvé la facturación antes de vender</h2>
<p>En Guatemala la facturación electrónica en línea (FEL) es obligatoria y se emite a través de un certificador autorizado por la SAT. El comprobante que genera la tienda cuando alguien compra <strong>no es una factura</strong>: es un recibo de pedido.</p>
<p>Hay dos caminos. El manual, que funciona bien cuando tenés pocos pedidos: recibís el pedido y emitís la factura desde el sistema de tu certificador. Y el automatizado, que conecta la tienda con el certificador mediante una integración. Definí cuál vas a usar desde el inicio y qué datos fiscales le vas a pedir al cliente durante la compra, para no andar persiguiendo NIT después.</p>

<h2>Paso 9: Probá, publicá y medí</h2>
<p>Antes de anunciar la tienda, hacé al menos tres compras de prueba completas desde un celular: una con transferencia, una contra entrega y, si la activaste, una con tarjeta. Revisá que lleguen los correos de confirmación, que el costo de envío sea el correcto y que el pedido aparezca completo en el panel.</p>
<p>Después de publicar, mirá dos números cada semana: cuánta gente llega a la tienda y cuántos completan la compra. Si entra mucha gente y nadie compra, el problema está en el precio, en el envío o en la confianza. Si no entra nadie, el problema es de difusión, no de la tienda.</p>

